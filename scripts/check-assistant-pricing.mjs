import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { stripTypeScriptTypes } from 'node:module';

const encode=code=>'data:text/javascript;base64,'+Buffer.from(code).toString('base64');
const compile=source=>stripTypeScriptTypes(source,{mode:'strip'});
const metricsUrl=encode(compile(await readFile(new URL('../src/assistantMetrics.ts',import.meta.url),'utf8')));
const source=compile(await readFile(new URL('../src/assistantPricing.ts',import.meta.url),'utf8')).replace("'./assistantMetrics'",JSON.stringify(metricsUrl));
const {costMetrics,money,hasPricingChange,proposalMatchesSettings}=await import(encode(source));
const {tokenMetrics,withTaskScope}=await import(metricsUrl);
const bill=(currency='CNY',total=1)=>({status:'calculated',currency,total,inputCost:total*.6,cachedCost:total*.1,outputCost:total*.3,model:'synthetic-model'});
const request=billing=>({usage:{prompt_tokens:100,completion_tokens:10,prompt_cache_hit_tokens:20},billing});
const raw=[{round:1,requests:[request(bill()),request(bill('CNY',2))]},{kind:'intent',requests:[request(bill('USD',.5))]}];
const result=costMetrics(raw);
assert.equal(result.records.length,3);assert.equal(result.missing,0);assert.equal(result.totals.find(t=>t.currency==='CNY').total,3);assert.equal(result.totals.find(t=>t.currency==='USD').total,.5);
assert.equal(tokenMetrics(raw).read,300);assert.equal(tokenMetrics(raw).written,30);
assert.equal(costMetrics(withTaskScope(raw,'a')).totals[0].total,3);
assert.equal(costMetrics([raw,withTaskScope(raw,'b')]).totals[0].total,6);
const incomplete=costMetrics([request(bill()),request(undefined),request({status:'unavailable',reason:'missing_calendar'}),request(bill('CNY',NaN))]);
assert.equal(incomplete.missing,3);assert.equal(incomplete.totals[0].total,1);
assert.equal(costMetrics([request({...bill(),total:2})]).missing,1);
assert.equal(costMetrics([request(bill('EUR'))]).missing,1);
assert.equal(costMetrics([request(bill('CNY',0))]).totals[0].total,0);
assert.equal(costMetrics([]).records.length,0);
assert.equal(money(.000001,'CNY'),'¥<0.0001');assert.equal(money(0,'USD'),'$0.0000');
const historical=structuredClone(raw);raw[0].requests[0].billing.total=200;
assert.equal(costMetrics(historical).totals[0].total,3);
const defaults=JSON.parse(await readFile(new URL('../src/assistantPricingDefaults.json',import.meta.url),'utf8'));
assert.equal(defaults.rules[0].inputPerMillion,2);assert.equal(defaults.rules[0].cachedInputPerMillion,.04);assert.equal(defaults.rules[0].outputPerMillion,8);assert(defaults.holidays['2026'].includes('2026-10-07'));
const ordinary={id:'test',before:{theme:'light',modelPricing:defaults},after:{theme:'dark',modelPricing:defaults}};
assert.equal(hasPricingChange(ordinary),false);assert.equal(proposalMatchesSettings(ordinary,{theme:'light',modelPricing:defaults}),false);assert.equal(proposalMatchesSettings(ordinary,{theme:'dark',modelPricing:defaults}),true);
const newPricing=structuredClone(defaults);newPricing.rules[0].outputPerMillion=10;
assert.equal(hasPricingChange({id:'price',before:{modelPricing:defaults},after:{modelPricing:newPricing}}),true);
console.log('Assistant pricing checks passed: requests, currencies, unknown data, precision, history, defaults.');
